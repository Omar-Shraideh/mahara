function make(lang) {
  var table = S[lang] || S.en;
  return function t(key, vars) {
    var s = table[key];
    if (s == null) s = S.en[key];
    if (s == null) return key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split("{" + k + "}").join(String(vars[k])); });
    return s;
  };
}

function formatNumber(n, lang, opts) {
  try { return new Intl.NumberFormat(lang === "ar" ? "ar-JO-u-nu-latn" : "en-GB", opts).format(n); }
  catch (e) { return String(n); }
}

function formatDate(ms, lang) {
  if (!ms) return "";
  try { return new Intl.DateTimeFormat(lang === "ar" ? "ar-JO-u-nu-latn" : "en-GB", { day: "numeric", month: "short", year: "numeric" }).format(new Date(ms)); }
  catch (e) { return new Date(ms).toISOString().slice(0, 10); }
}

var api = { STRINGS: S, make: make, formatNumber: formatNumber, formatDate: formatDate };
export default api;
